import { appHtml } from "./app-html.generated.js";
import type { SequenzyMcpProfile } from "./tools/profiles.js";

export const APP_RESOURCE_URI = "ui://sequenzy/previews-v1.html";
export const APP_MIME_TYPE = "text/html;profile=mcp-app";
export const appResource = {
  uri: APP_RESOURCE_URI,
  name: "Sequenzy email and sequence previews",
  mimeType: APP_MIME_TYPE,
  description: "Preview rendered emails and explore saved sequence flows.",
};

/**
 * Image origins the OpenAI host allows in email previews. Its scanner rejects
 * scheme wildcards such as "https:", so list Sequenzy's upload host and the
 * stock-photo hosts the editor offers; other external images show alt text.
 */
export const OPENAI_APP_RESOURCE_DOMAINS = [
  "https://images.sequenzy.com",
  // Countdown timer GIFs are generated by the API.
  "https://api.sequenzy.com",
  "https://images.pexels.com",
  "https://images.unsplash.com",
  "https://plus.unsplash.com",
];

/**
 * Dedicated origin ChatGPT hosts the widget under. Plugin submission requires
 * one per plugin; it is the registrable parent of the verified MCP host.
 */
export const OPENAI_APP_WIDGET_DOMAIN = "https://sequenzy.com";

export function readAppResource(profile: SequenzyMcpProfile = "standard") {
  const isOpenAi = profile === "openai";
  const resourceDomains = isOpenAi ? OPENAI_APP_RESOURCE_DOMAINS : ["https:"];
  return {
    contents: [
      {
        ...appResource,
        text: appHtml,
        _meta: {
          ui: {
            ...(isOpenAi ? { domain: OPENAI_APP_WIDGET_DOMAIN } : {}),
            csp: { connectDomains: [], resourceDomains },
          },
          ...(isOpenAi
            ? { "openai/widgetDomain": OPENAI_APP_WIDGET_DOMAIN }
            : {}),
        },
      },
    ],
  };
}
