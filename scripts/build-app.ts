import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";

const source = new URL("../ui/app.ts", import.meta.url);
const shell = await readFile(
  new URL("../ui/shell.html", import.meta.url),
  "utf8"
);
const digest = createHash("sha256");
for (const filename of (
  await readdir(new URL("../ui/", import.meta.url))
).sort()) {
  digest
    .update(filename)
    .update(await readFile(new URL(`../ui/${filename}`, import.meta.url)));
}
const fingerprint = digest
  .update(await readFile(new URL(import.meta.url)))
  .digest("hex");
const marker = `// Source SHA256: ${fingerprint}`;
const output = new URL("../src/app-html.generated.ts", import.meta.url);

if (process.argv.includes("--check")) {
  // Source fingerprints remain stable across Bun minifier versions. The
  // committed bundle is the runtime artifact; rebuilding is a deliberate edit.
  if (!(await readFile(output, "utf8")).startsWith(`${marker}\n`)) {
    throw new Error(
      "MCP app bundle is stale. Run bun run build:app and commit the generated file."
    );
  }
} else {
  const result = await Bun.build({
    entrypoints: [source.pathname],
    target: "browser",
    minify: true,
  });
  if (!result.success)
    throw new AggregateError(result.logs, "MCP app build failed");
  const script = await result.outputs[0].text();
  const logo = (
    await readFile(new URL("../ui/logo.png", import.meta.url))
  ).toString("base64");
  const styles = await readFile(
    new URL("../ui/styles.css", import.meta.url),
    "utf8"
  );
  const html = shell
    .replace("/* APP_SCRIPT */", () =>
      script.replace(/<\/script/gi, "<\\/script")
    )
    .replace("/* APP_STYLES */", () => styles)
    .replace("/* APP_LOGO */", `data:image/png;base64,${logo}`);
  await writeFile(
    output,
    `${marker}\n// Generated by bun run build:app. Commit this file; bundled hosts need no filesystem assets.\nexport const appHtml = ${JSON.stringify(html)};\n`
  );
}
